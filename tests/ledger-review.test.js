const { test } = require('node:test');
const assert = require('node:assert/strict');
const { EventEmitter } = require('events');
const Module = require('module');
const { Ledger } = require('../src/core/ledger');
const fs = require('fs');
const os = require('os');
const path = require('path');
const handlers = {};
const dialogParents = [];
const original = Module._load;
Module._load = function(id, ...rest) { if (id === 'electron') return { ipcMain: { handle: (key, fn) => { handlers[key] = fn; } }, dialog: { showMessageBox: async parent => { dialogParents.push(parent); return { response: 1 }; } } }; return original.call(this, id, ...rest); };
const { LedgerUI } = require('../src/main/ledger-review');
const { OliveWindow } = require('../src/main/window');
Module._load = original;
const { fakeBrowser, FakeWindow, eventFrom } = require('./helpers/fake-browser');

test('olive://ledger is a tab: ipc trusts only its main frame, follows the manager ledger, private windows hand off', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'olive-ledger-ui-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const mgr = fakeBrowser({ ledger: new Ledger(path.join(dir, 'one.json')) });
  const priv = new FakeWindow(mgr, { isPrivate: true }), owner = new FakeWindow(mgr);
  const ui = new LedgerUI(mgr);
  mgr.focused = priv;
  const tab = ui.show(priv);
  assert.equal(tab.url, 'olive://ledger'); assert.ok(owner.tabs.has(tab.id), 'a private window opens it in a normal window');
  assert.equal(ui.show(owner), tab, 'the menu focuses the open ledger tab');
  const invoke = handlers['olive:ledger'];
  const web = owner.createTab({ url: 'https://example.com/' });
  assert.equal(await invoke(eventFrom(web), 'get'), null, 'web page');
  assert.equal(await invoke(eventFrom(tab, { url: 'olive://ledger' }), 'get'), null, 'subframe');
  mgr.ledger.record('visit', { url: 'https://example.com/?secret=hidden' });
  let state = await invoke(eventFrom(tab), 'get'); assert.equal(state.total, 1);
  mgr.ledger.flush();
  mgr.ledger = new Ledger(path.join(dir, 'two.json'));
  state = await invoke(eventFrom(tab), 'get'); assert.equal(state.total, 0);
  mgr.ledger.record('permission', { permission: 'camera', allowed: true });
  state = await invoke(eventFrom(tab), 'delete', { filter: {} }); assert.equal(state.total, 0);
  assert.equal(dialogParents.at(-1), owner.win, 'the confirm sheets on the tab\'s window');
  assert.equal(await invoke(eventFrom(tab), 'close'), null, 'no close action: it is a tab (cmd+w)');
  assert.ok(owner.tabs.has(tab.id));
  owner.navigate(tab, 'https://elsewhere.example/');
  assert.equal(await invoke(eventFrom(tab), 'get'), null, 'navigated away: no ledger');
  ui.dispose();
  mgr.ledger.close();
});
test('window hook blocks every private event and adds window id to normal metadata', () => {
  const calls = [];
  const owner = { isPrivate: true, id: 42, mgr: { ledger: { record: (...args) => calls.push(args) } } };
  OliveWindow.prototype.recordActivity.call(owner, 'visit', { url: 'https://private.example/' });
  assert.equal(calls.length, 0);
  owner.isPrivate = false;
  OliveWindow.prototype.recordActivity.call(owner, 'tab-open', { tabId: 7 });
  assert.deepEqual(calls, [['tab-open', { tabId: 7, windowId: 42 }]]);
});
