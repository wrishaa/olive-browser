// Dev only: no access to real Olive cookies or devices.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import { chromium } from 'playwright-core';
assert(process.env.OLIVE_PROFILE && process.env.OLIVE_PROFILE !== 'default', 'use OLIVE_PROFILE=dev');
const info = JSON.parse(fs.readFileSync(`${os.homedir()}/Library/Application Support/Olive-${process.env.OLIVE_PROFILE}/agent.json`));
const token = fs.readFileSync(info.tokenFile,'utf8').trim();
const api = async(p,body)=> (await fetch(info.api+p,{method:body?'POST':'GET',headers:{authorization:`Bearer ${token}`,'content-type':'application/json'},body:body?JSON.stringify(body):undefined})).json();
const browser = await chromium.connectOverCDP(info.cdp);
const pages = ()=>browser.contexts().flatMap(c=>c.pages());
const wait = async(test)=>{for(let i=0;i<100;i++){const r=await test();if(r)return r;await new Promise(r=>setTimeout(r,100));}throw new Error('timed out');};
const ui = pages().find(p=>p.url().includes('/ui/index.html'));
const tab = await api('/tabs',{url:'https://permission.site/'});
try {
  const page = await wait(()=>pages().find(p=>p.url().startsWith('https://permission.site/')));
  await page.waitForLoadState('domcontentloaded');
  await ui.evaluate(()=>olive.cmd('resetPermissions'));
  await ui.getByRole('button',{name:'Site settings',exact:true}).click();
  let settings = await wait(()=>pages().find(p=>p.url().endsWith('/site-settings.html')));
  await settings.getByLabel('Microphone',{exact:true}).selectOption('allow');
  await wait(async()=>await settings.getByLabel('Microphone',{exact:true}).inputValue()==='allow');
  let state=await settings.evaluate(()=>siteSettings.get());
  assert.equal(state.origin,'https://permission.site');
  assert.equal(state.permissions.find(p=>p.key==='media:audio').value,'allow');
  await settings.getByLabel('Camera',{exact:true}).selectOption('block');
  await wait(async()=>!(await settings.getByLabel('Camera',{exact:true}).isDisabled()));
  await settings.getByLabel('Screen sharing',{exact:true}).selectOption('ask');
  await wait(async()=>!(await settings.getByLabel('Screen sharing',{exact:true}).isDisabled()));
  state=await settings.evaluate(()=>siteSettings.get());
  assert.equal(state.permissions.find(p=>p.key==='media:video').value,'block');
  assert(['granted','denied','not-determined','restricted','unknown'].includes(state.system.microphone));
  console.log('ok: lock button; microphone allow, camera block, screen ask; macOS status; permission persistence');
  await settings.close();
  await page.evaluate(()=>{window.result=null;Notification.requestPermission().then(v=>result=v);});
  const toast = await wait(async()=>{const t=pages().find(p=>p.url().endsWith('/permissions.html'));return t && await t.getByRole('button',{name:'Allow once',exact:true}).count()?t:null;});
  await toast.locator('.card:not(.leaving)').getByRole('button',{name:'Allow once',exact:true}).click();
  await wait(()=>page.evaluate(()=>result==='granted'));
  const saved = JSON.parse(fs.readFileSync(`${info.userData}/permissions.json`));
  assert.equal(saved['https://permission.site|notifications'],undefined);
  await page.reload();
  await page.evaluate(()=>{window.result=null;Notification.requestPermission().then(v=>result=v);});
  await wait(async()=>await toast.locator('.card:not(.leaving)').getByRole('button',{name:'Block',exact:true}).count());
  await toast.locator('.card:not(.leaving)').getByRole('button',{name:'Block',exact:true}).click();
  await wait(()=>page.evaluate(()=>result==='denied'));
  console.log('ok: allow once resolves real notification API, not saved, expires on reload; block works');
  await ui.getByRole('button',{name:'Site settings',exact:true}).click();
  settings=await wait(()=>pages().find(p=>p.url().endsWith('/site-settings.html')));
  assert.equal((await settings.evaluate(()=>siteSettings.get())).permissions.find(p=>p.key==='media:audio').value,'allow');
  await page.goto('https://example.com/');
  await wait(()=>settings.isClosed());
  console.log('ok: site settings closes on navigation, no stale-origin changes');
} finally { await api(`/tabs/${tab.id}/close`,{}); await browser.close(); }
